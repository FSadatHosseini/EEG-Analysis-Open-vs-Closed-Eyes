import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import spectrogram

sfreq = raw_open_avg.info["sfreq"]

def get_spectrogram(raw):
    segment = raw.copy().crop(tmin=5, tmax=55)
    signal = segment.get_data(picks=["Oz"])[0]

    freqs, times, power = spectrogram(
        signal,
        fs=sfreq,
        window="hann",
        nperseg=int(2 * sfreq),
        noverlap=int(1.5 * sfreq),
        nfft=512,
        scaling="density",
        mode="psd"
    )

    return freqs, times + 5, 10 * np.log10(power + 1e-20)

freqs_open, times_open, power_open = get_spectrogram(raw_open_avg)
freqs_closed, times_closed, power_closed = get_spectrogram(raw_closed_avg)

