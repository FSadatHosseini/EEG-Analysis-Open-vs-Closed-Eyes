"""# 4. Estimate Welch PSD"""

tmin, tmax = 5, 55
sfreq = raw_open_clean.info["sfreq"]


n_per_seg = int(4 * sfreq)
n_overlap = n_per_seg // 2
n_fft = 1024


posterior_channels = ["Pz", "P3", "P4", "P7", "P8", "O1", "Oz", "O2"]

def calculate_psd(raw, channel_names):
    segment = raw.copy().crop(tmin=tmin, tmax=tmax)
    data = segment.get_data(picks=channel_names)

    freqs, psd = welch(
        data,
        fs=sfreq,
        window="hann",
        nperseg=n_per_seg,
        noverlap=n_overlap,
        nfft=n_fft,
        axis=-1
    )

    return freqs, psd


