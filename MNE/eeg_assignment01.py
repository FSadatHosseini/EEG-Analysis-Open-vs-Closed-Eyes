"""# 5. Compute Spectral Features"""

bands = {
    "delta": (1, 4),
    "theta": (4, 8),
    "alpha": (8, 13),
    "beta": (13, 30)
}

def spectral_features(raw, condition):
    segment = raw.copy().crop(tmin=5, tmax=55)
    data = segment.get_data()
    ch_names = segment.ch_names
    rows = []

    for i, channel in enumerate(ch_names):
        freqs, psd = welch(
            data[i],
            fs=sfreq,
            window="hann",
            nperseg=n_per_seg,
            noverlap=n_overlap,
            nfft=n_fft
        )

        band_power = {}
        for band, (low, high) in bands.items():
            mask = (freqs >= low) & (freqs < high)
            band_power[band] = trapezoid(psd[mask], freqs[mask])

        total_power = sum(band_power.values())
        rel_alpha = (
            band_power["alpha"] / total_power
            if total_power > 0 else np.nan
        )

        alpha_mask = (freqs >= 8) & (freqs <= 13)
        alpha_freqs = freqs[alpha_mask]
        alpha_psd = psd[alpha_mask]

        alpha_peak_freq = (
            alpha_freqs[np.argmax(alpha_psd)]
            if len(alpha_psd) else np.nan
        )

        rows.append({
            "condition": condition,
            "channel": channel,
            "delta": band_power["delta"],
            "theta": band_power["theta"],
            "alpha": band_power["alpha"],
            "beta": band_power["beta"],
            "rel_alpha": rel_alpha,
            "alpha_peak_freq": alpha_peak_freq
        })

    return rows

rows = []
